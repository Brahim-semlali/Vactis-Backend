-- VACTIS - Script de création de la base de données (PostgreSQL)
-- Utilisation : psql -U postgres -d vactis_db -f database/vactis_schema.sql

START TRANSACTION;


-- ============================================================================
--  Sécurité, utilisateurs et menus
-- ============================================================================

-- Rôles applicatifs (ADMIN, COMMERCIAL, ...)
CREATE TABLE roles (
    id_role      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    description  varchar(255),
    name_role    varchar(255)
);

-- Comptes utilisateurs ; mot de passe chiffré BCrypt
CREATE TABLE users (
    id                     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_locked         boolean NOT NULL,
    created_at             timestamp(6) NOT NULL,
    email                  varchar(255) UNIQUE,
    enabled                boolean NOT NULL,
    failed_login_attempts  integer NOT NULL,
    first_name             varchar(255),
    last_login_at          timestamp(6),
    last_name              varchar(255),
    locked_at              timestamp(6),
    locked_until           integer,
    password               varchar(255) NOT NULL,
    phone                  varchar(255),
    updated_at             timestamp(6) NOT NULL,
    username               varchar(255) NOT NULL UNIQUE,
    id_role                bigint REFERENCES roles (id_role),
    avatar                 text
);

-- Règles de verrouillage des comptes (ligne unique, id = 1)
CREATE TABLE auth_settings (
    id                     bigint PRIMARY KEY,
    lock_duration_minutes  integer NOT NULL,
    max_failed_attempts    integer NOT NULL
);

-- Rubriques principales du menu latéral
CREATE TABLE menu_principal (
    id_menu_princ  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    icone          varchar(255),
    nom            varchar(255),
    menu_order     integer
);

-- Sous-menus ; chacun correspond à une route du frontend
CREATE TABLE menu_items (
    id_menu        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    icon           varchar(255),
    is_visible     boolean,
    label          varchar(255),
    menu_order     integer,
    route          varchar(255),
    id_menu_princ  bigint REFERENCES menu_principal (id_menu_princ)
);

-- Sous-menus autorisés pour chaque rôle
CREATE TABLE role_menu (
    id_role  bigint NOT NULL REFERENCES roles (id_role),
    id_menu  bigint NOT NULL REFERENCES menu_items (id_menu)
);

-- Journal des connexions
CREATE TABLE connexion_logs (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    adresse_ip        varchar(255),
    date_connexion    timestamp(6) NOT NULL,
    date_deconnexion  timestamp(6),
    succes            boolean NOT NULL,
    user_id           bigint
);

-- Notifications destinées aux utilisateurs
CREATE TABLE notifications (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at    timestamp(6) NOT NULL,
    lu            boolean NOT NULL,
    message       varchar(2000) NOT NULL,
    reference_id  bigint,
    titre         varchar(255) NOT NULL,
    type          varchar(255),
    user_id       bigint NOT NULL REFERENCES users (id)
);

-- Paramètres système (session, mots de passe, laboratoire, objectif)
CREATE TABLE system_settings (
    id                             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    duree_inactivite_jours         integer NOT NULL,
    duree_session_minutes          integer NOT NULL,
    updated_at                     timestamp(6) NOT NULL,
    updated_by_id                  bigint REFERENCES users (id),
    duree_blocage_minutes          integer,
    journal_connexion_actif        boolean,
    max_tentatives_connexion       integer,
    mdp_exige_caractere_special    boolean,
    mdp_exige_chiffre              boolean,
    mdp_exige_majuscules           boolean,
    mdp_longueur_minimale          integer,
    bridge_goal_target             bigint,
    laboratoire_latitude           double precision,
    laboratoire_longitude          double precision,
    bridge_goal_input_value        numeric(14,2),
    bridge_goal_method             varchar(20),
    bridge_goal_reference_revenue  bigint
);

-- ============================================================================
--  Données métier
-- ============================================================================

-- Médecins prescripteurs et indicateurs calculés par le moteur VACTIS
CREATE TABLE medecins (
    id                             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ca_mois                        integer,
    code_medecin                   varchar(20) NOT NULL UNIQUE,
    commentaire                    text,
    commercial_referent            varchar(255),
    created_at                     timestamp(6) NOT NULL,
    date_derniere_activite         date,
    date_premiere_collaboration    date,
    email                          varchar(255),
    nom                            varchar(255) NOT NULL,
    organisme                      varchar(255) NOT NULL,
    prenom                         varchar(255) NOT NULL,
    risque_urgence                 varchar(20) NOT NULL,
    segment                        varchar(30),
    specialite                     varchar(255) NOT NULL,
    statut                         varchar(20) NOT NULL,
    statut_pilotage                varchar(30) NOT NULL,
    telephone                      varchar(20),
    updated_at                     timestamp(6) NOT NULL,
    ville                          varchar(100),
    note_input                     double precision,
    score_valeur                   double precision,
    ca_baseline                    integer,
    ca_total                       integer,
    total_cas                      integer,
    baisse_courte                  double precision,
    baisse_reference               double precision,
    ca_mensuel_moyen               double precision,
    fiabilite                      varchar(255),
    intervalle_effectif            double precision,
    jours_sans_activite            integer,
    performance_sur100             double precision,
    poids_eco_sur100               double precision,
    potentiel_sur100               double precision,
    reference_ca                   double precision,
    reference_volume               double precision,
    score_risque                   double precision,
    score_silence                  double precision,
    variation_ca                   double precision,
    variation_mixte_sur100         double precision,
    variation_volume               double precision,
    intensite_risque               double precision,
    score_urgence                  double precision,
    tendance_risque                double precision,
    is_a_reactiver_manuel          boolean DEFAULT false,
    is_profil_irregulier           boolean DEFAULT false,
    latitude                       double precision,
    longitude                      double precision,
    niveau_intensite               varchar(20),
    ca_mois_analyse                double precision,
    cas_mois_analyse               double precision,
    classe_silence                 varchar(255),
    date_derniere_activite_calcul  date,
    date_reference_indicateurs     date,
    facteur_materialite            double precision,
    nombre_mois_reference          integer,
    perte_ca                       double precision,
    rang_urgence                   integer,
    seuil_impact                   double precision,
    source_rythme                  varchar(255),
    urgence_brute                  double precision
);

-- Dossiers d'analyses importés depuis l'extraction Excel
CREATE TABLE data_fictif (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date_prelevement   date,
    date_reception     date NOT NULL,
    lieu_prelevement   varchar(255) NOT NULL,
    montant_rembourse  integer NOT NULL,
    nombre_analyses    integer NOT NULL,
    patient_ref        varchar(30),
    prix_a_payer       integer NOT NULL,
    prix_total         integer NOT NULL,
    reference_dossier  varchar(50) NOT NULL UNIQUE,
    statut_dossier     varchar(30) NOT NULL,
    type_analyse       varchar(255) NOT NULL,
    urgent             boolean NOT NULL,
    medecin_id         bigint REFERENCES medecins (id)
);

-- Actions commerciales générées ou saisies
CREATE TABLE actions (
    id                       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    action_recommandee       varchar(255) NOT NULL,
    backlog                  boolean NOT NULL,
    commentaire              text,
    commercial               varchar(255) NOT NULL,
    created_at               timestamp(6) NOT NULL,
    cycle_mensuel            varchar(20),
    date_visite              date,
    etat_action              varchar(20) NOT NULL,
    lieu_organisme           varchar(255) NOT NULL,
    segment                  varchar(30),
    statut                   varchar(30) NOT NULL,
    updated_at               timestamp(6) NOT NULL,
    urgence                  varchar(30) NOT NULL,
    urgence_silence          boolean NOT NULL,
    medecin_id               bigint NOT NULL REFERENCES medecins (id),
    date_prochaine_action    date,
    motif_non_realisation    text,
    prochaine_action         varchar(255),
    qualification            varchar(50),
    reserved_at              timestamp(6),
    reserved_by              varchar(255),
    is_reserved              boolean,
    action_parente_id        bigint,
    date_echeance            date,
    est_en_retard            boolean,
    horizon_jours            integer,
    obstacle_principal       varchar(30),
    statut_plan_retention    varchar(30),
    type_etape_retention     varchar(30),
    date_depart              date,
    date_retour_prevue       date,
    date_revue               date,
    decision_recommandation  varchar(40),
    reclamation_id           bigint,
    source_recommandation    varchar(40),
    suspension_levee         boolean
);

-- Comptes rendus de visite des commerciaux
CREATE TABLE retours_terrain (
    id                     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    commentaire            text,
    created_at             timestamp(6) NOT NULL,
    date_visite            date NOT NULL,
    note                   double precision,
    visiteur               varchar(255),
    medecin_id             bigint NOT NULL REFERENCES medecins (id),
    nom_medecin            varchar(255),
    qualification          varchar(20) DEFAULT 'NON_RENSEIGNE' NOT NULL,
    reclamation            boolean DEFAULT false NOT NULL,
    statut_visite          varchar(20) DEFAULT 'REALISEE' NOT NULL,
    type_visite            varchar(30),
    action_id              bigint REFERENCES actions (id),
    date_prochaine_action  date,
    motif_non_realisation  text,
    prochaine_action       varchar(255),
    obstacle_principal     varchar(30),
    date_depart            date,
    date_retour_prevue     date,
    date_revue             date
);

-- Réclamations des médecins
CREATE TABLE reclamations (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    categorie               varchar(30) NOT NULL,
    commercial_declarant    varchar(255) NOT NULL,
    created_at              timestamp(6) NOT NULL,
    date_declaration        date NOT NULL,
    date_resolution         date,
    date_echeance           date,
    description             text NOT NULL,
    priorite                varchar(20) NOT NULL,
    responsable_traitement  varchar(255),
    retour_terrain_id       bigint,
    solution_apportee       text,
    statut                  varchar(20) NOT NULL,
    updated_at              timestamp(6) NOT NULL,
    medecin_id              bigint NOT NULL REFERENCES medecins (id),
    date_visite             date,
    prochaine_instruction   text
);

-- Historique des changements de statut des réclamations
CREATE TABLE reclamation_historique (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ancien_statut   varchar(30),
    auteur          varchar(255) NOT NULL,
    commentaire     text,
    created_at      timestamp(6) NOT NULL,
    nouveau_statut  varchar(30) NOT NULL,
    reclamation_id  bigint NOT NULL REFERENCES reclamations (id)
);

-- Alertes de silence et de rupture de rythme
CREATE TABLE alertes_hebdomadaires (
    id                     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    action_generee_id      bigint,
    date_detection         date NOT NULL,
    intervalle_moyen       double precision,
    jours_silence          integer,
    message                varchar(500),
    score_urgence_silence  double precision,
    statut_alerte          varchar(30),
    type_alerte            varchar(30),
    medecin_id             bigint NOT NULL REFERENCES medecins (id)
);

-- Seuils de chiffre d'affaires par statut et segment
CREATE TABLE controle (
    id_controle  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    maxca        bigint,
    minca        bigint,
    type         varchar(255),
    actif        boolean,
    etat         varchar(255)
);

-- Objectifs mensuels du Bridge to Goal
CREATE TABLE bridge_goal_targets (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    input_value             numeric(14,2) NOT NULL,
    method                  varchar(20) NOT NULL,
    period                  varchar(7) NOT NULL UNIQUE,
    previous_month_revenue  bigint NOT NULL,
    target_amount           bigint NOT NULL,
    updated_at              timestamp(6) NOT NULL
);

-- Agences concurrentes affichées sur la carte
CREATE TABLE agences_concurrentes (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    adresse        varchar(500),
    created_at     timestamp(6) NOT NULL,
    enseigne       varchar(255),
    latitude       double precision NOT NULL,
    longitude      double precision NOT NULL,
    nom            varchar(255) NOT NULL,
    notes          text,
    updated_at     timestamp(6) NOT NULL,
    created_by_id  bigint REFERENCES users (id),
    updated_by_id  bigint REFERENCES users (id)
);

COMMIT;
